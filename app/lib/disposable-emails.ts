// The throwaway service an email address belongs to, or null.
export function disposableDomain(email: string): string | null {
  const at = email.lastIndexOf("@");
  if (at < 0) return null;
  let domain = email.slice(at + 1).trim().toLowerCase().replace(/\.$/, "");
  while (domain.includes(".")) {
    if (DISPOSABLE_EMAIL_DOMAINS.has(domain)) return domain;
    domain = domain.slice(domain.indexOf(".") + 1);
  }
  return null;
}
